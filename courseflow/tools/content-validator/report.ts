  L.push("| Có chấm điểm | Có (0–100, có trọng số) | **Không bao giờ** chấm tự động |");
  L.push("| Ví dụ | Bài có mục Tóm tắt, % bài có câu hỏi chấm được, liên kết hỏng | Nội dung có đúng không, bài có bám mục tiêu không, thứ tự dạy có hợp lý không, đáp án có đúng không |");
  L.push("");
  L.push("Điểm tự động cao **không** có nghĩa là khóa học tốt: một khóa đầy đủ cấu trúc vẫn có thể sai kiến thức. Ngược lại điểm thấp thường chỉ ra khóa còn thiếu khung (mô tả, mục tiêu, câu hỏi…) hoặc có bài quá mỏng. Vì vậy với mỗi khóa, báo cáo kèm bảng kiểm bốn câu hỏi cần người rà soát, hiển thị mục tiêu học tập cạnh danh sách module để người đọc đối chiếu, và một vài bài nên mở xem đầu tiên (chọn tự động theo số liệu, không đọc nội dung).");
  L.push("");
  L.push("### 5.2 Cách tính điểm");
  L.push("");
  L.push("Mỗi khóa có 7 nhóm tiêu chí, mỗi nhóm chấm 0–100 từ các tiêu chí con; điểm tổng = tổng (điểm nhóm × trọng số) / 100. Mọi bài học dùng ở đây là bài loại `lesson` (không tính file tổng quan/tài nguyên).");
  L.push("");
  L.push("| Nhóm | Trọng số | Nội dung đo |");
  L.push("|---|---:|---|");
  for (const d of AREAS) L.push(`| ${d.label} | ${d.weight} | ${d.what} |`);
  L.push("");
  L.push("Chi tiết từng nhóm (điểm tiêu chí con; “đạt mục tiêu” nghĩa là được điểm tối đa, thấp hơn thì tỉ lệ thuận):");
  L.push("");
  L.push("| Nhóm | Tiêu chí con (trọng số) | Cách chấm |");
  L.push("|---|---|---|");
  L.push("| Metadata | tiêu đề riêng (15), mô tả (20), mục tiêu (25), điều kiện tiên quyết (15), README (15), ngôn ngữ (5), cấp độ (5) | mỗi tiêu chí 0 hoặc 100. “Tiêu đề lấy từ tên thư mục” = tên thư mục là slug (không có khoảng trắng) và tiêu đề trùng slug đó (có hoặc không thay `-`/`_` bằng khoảng trắng). Tên thư mục dạng “17-Complete Modern C++” là tiêu đề đọc được nên không bị coi là slug |");
  L.push(`| Cấu trúc | độ dài bài (40), cân đối module (20), bài có H1 (15), thứ tự file (15), thư mục rỗng (10) | độ dài = 60% × (100 − % bài < ${TARGETS.shortWords} từ) + 40% × điểm trung vị đạt ${TARGETS.medianWords} từ; module = 100 × (1 − tỉ lệ module chỉ 1 bài), tối đa 60 nếu chỉ có 1 module cho > ${TARGETS.longFlatCourse} bài; H1 = 100 − % bài thiếu H1; thứ tự = 100 × (1 − module không đánh số/tổng module); thư mục rỗng = 100 − 34 × số thư mục |`);
  L.push(`| Tiêu đề | không trùng trong module (50), không chỉ là tên file/mã (50) | 100 × (1 − min(1, ${TARGETS.fragmentFactor} × tỉ lệ bài có vấn đề)). “Tên file/mã”: tiêu đề kiểu \`x.md\`, \`UD12-S01-L003\`, “Lesson 3”, “Part 1”, \`ten_file_slug\`; bài thiếu H1 được tính riêng ở nhóm Cấu trúc nên không bị trừ hai lần |`);
