  L.push(`| Liên kết & trùng lặp | liên kết hỏng (60), nội dung trùng hoàn toàn (40) | 100 × (1 − min(1, ${TARGETS.linkFactor} × tỉ lệ bài bị ảnh hưởng)); lấy từ mã \`broken-link\`, \`duplicate-content\` của scanner |`);
