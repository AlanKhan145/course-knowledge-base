  L.push("## 3. Theo lĩnh vực");
  L.push("");
  L.push("| Lĩnh vực | Số khóa | Số bài | Điểm TB | Trung vị | Tốt | Khá | Cần cải thiện | Yếu | Trong top 50 yếu nhất | Nhóm yếu nhất |");
  L.push("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|");
  for (const d of dom) L.push(`| ${mdCell(d.title)} | ${fmtNum(d.courses)} | ${fmtNum(d.lessons)} | ${score1(d.avgScore)} | ${score1(d.medianScore)} | ${d.good} | ${d.fair} | ${d.needs} | ${d.poor} | ${d.inWorst50} | ${mdCell(d.weakestArea)} |`);
  L.push("");

  L.push("## 4. Gợi ý cải thiện phổ biến nhất");
  L.push("");
  L.push("| Gợi ý | Số khóa bị ảnh hưởng | Tổng số mục (bài/module/…) |");
  L.push("|---|---:|---:|");
  for (const g of s.suggestionCodes) L.push(`| ${mdCell(g.label)} (${code(g.code)}) | ${fmtNum(g.courses)} | ${fmtNum(g.items)} |`);
  L.push("");

  L.push("## 5. Phương pháp");
  L.push("");
  L.push("### 5.1 Hai loại kiểm tra: tự động và cần con người");
  L.push("");
