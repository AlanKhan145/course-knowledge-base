export function renderCourseReport(item: Item, samples: ReviewSample[], ctx: RenderContext): string {
  const { a, suggestions } = item;
  const c = a.course;
  const r = a.raw;
  const L: string[] = [];
  L.push(MARKER);
  L.push(`# Báo cáo chất lượng: ${c.title}`);
  L.push("");
  L.push("| | |");
  L.push("|---|---|");
  L.push(`| Mã khóa | ${code(c.id)} |`);
  L.push(`| Lĩnh vực › chuyên ngành | ${mdCell(c.domainTitle)} › ${mdCell(c.categoryTitle)} |`);
  L.push(`| Thư mục (trong kho Khóa học) | ${code(c.dir)} |`);
  L.push(`| Ngôn ngữ · trạng thái | ${mdCell(c.language ?? "?")} · ${mdCell(c.status)} |`);
  L.push(`| Quy mô | ${fmtNum(r.lessons)} bài · ${fmtNum(c.moduleCount)} module · ${fmtNum(r.words)} từ · ${fmtNum(r.questions)} câu hỏi |`);
  L.push(`| **Điểm tự động** | **${score1(a.score)} / 100 — ${a.label}** |`);
  L.push(`| Dữ liệu từ | catalog.db quét lúc ${ctx.lastScan ? dateVi(ctx.lastScan) : "không rõ"}; báo cáo sinh lúc ${dateVi(ctx.generatedAt)} |`);
  L.push("");
  L.push("> Điểm chỉ phản ánh các tiêu chí đo được tự động từ catalog. Nó **không** đánh giá độ đúng của nội dung, sự bám sát mục tiêu, thứ tự sư phạm hay độ đúng của đáp án — các mục đó nằm ở phần B và do người rà soát quyết định. Công cụ chỉ đọc catalog, không sửa bất kỳ file Markdown nào.");
  L.push("");

  // ---- A
  L.push("## A. Chỉ số tự động (đo được)");
  L.push("");
  L.push("| Nhóm | Điểm (0–100) | Trọng số | Đóng góp |");
  L.push("|---|---:|---:|---:|");
  for (const ar of a.areas) L.push(`| ${ar.label} | ${score1(ar.score)} | ${ar.weight} | ${score1((ar.score * ar.weight) / 100)} |`);
  L.push(`| **Tổng** | **${score1(a.score)}** | 100 | **${score1(a.score)}** |`);
  L.push("");
  for (const ar of a.areas) {
    L.push(`### ${ar.label} — ${score1(ar.score)}/100`);
    L.push("");
    L.push("| Tiêu chí | Điểm | Trọng số trong nhóm | Số liệu thô |");
    L.push("|---|---:|---:|---|");
    for (const p of ar.parts) L.push(`| ${mdCell(p.label)}${p.skipped ? " *(không tính điểm)*" : ""} | ${p.skipped ? "—" : score1(p.score)} | ${p.weight} | ${mdCell(p.raw)} |`);
    L.push("");
  }
  L.push("### Phân bố độ dài bài học");
  L.push("");
  L.push("| " + r.lengthBuckets.map((b) => b.label).join(" | ") + " |");
  L.push("|" + r.lengthBuckets.map(() => "---:").join("|") + "|");
  L.push("| " + r.lengthBuckets.map((b) => `${fmtNum(b.count)} (${fmtPct(pct(b.count, r.lessons))})`).join(" | ") + " |");
  L.push("");
  L.push(`Trung vị ${fmtNum(r.medianWords)} từ/bài; trung bình ${fmtNum(r.lessons ? r.words / r.lessons : 0)} từ/bài.`);
  L.push("");

  // ---- B
  L.push("## B. Cần con người rà soát (không chấm điểm)");
  L.push("");
  L.push("Bốn mục dưới đây cần phán đoán của người có chuyên môn; công cụ chỉ cung cấp dữ kiện để việc rà soát nhanh hơn.");
  L.push("");
  L.push("### Mục tiêu học tập và module");
  L.push("");
  if (c.objectives.length) {
    L.push("**Mục tiêu học tập khai báo:**");
    L.push("");
    c.objectives.forEach((o, i) => L.push(`${i + 1}. ${truncate(o, 220)}`));
  } else {
    L.push("**Khóa chưa khai báo mục tiêu học tập** → chưa thể đánh giá mức độ bám sát; hãy bổ sung mục tiêu trước (xem gợi ý ở phần C).");
  }
  L.push("");
  L.push("**Module** (cột cuối để người rà soát ghi số mục tiêu mà module phục vụ):");
  L.push("");
  const byModule = new Map<string, typeof c.lessons>();
  for (const l of c.lessons) {
    if (!l.moduleId) continue;
    const arr = byModule.get(l.moduleId);
    if (arr) arr.push(l);
    else byModule.set(l.moduleId, [l]);
  }
  const MAX_MODULES = 80;
  L.push("| # | Module | Số bài | Câu hỏi | Các bài đầu | Phục vụ mục tiêu |");
  L.push("|---:|---|---:|---:|---|---|");
  c.modules.slice(0, MAX_MODULES).forEach((m, i) => {
    const titles = (byModule.get(m.id) ?? []).slice(0, 4).map((l) => truncate(l.title, 42)).join("; ");
    L.push(`| ${i + 1} | ${mdCell(truncate(m.title, 70))} | ${m.lessonCount} | ${m.questionCount} | ${mdCell(titles)} | |`);
  });
  if (c.modules.length > MAX_MODULES) L.push(`| … | *còn ${c.modules.length - MAX_MODULES} module nữa* | | | | |`);
  L.push("");

  for (const q of REVIEW_QUESTIONS) {
    L.push(`### ${q.title}`);
    L.push("");
    for (const text of q.questions) L.push(`- [ ] ${text}`);
    if (q.key === "accuracy" && samples.length) {
      L.push("");
      L.push("Bài gợi ý mở đầu tiên khi rà soát mẫu (chọn tự động từ số liệu catalog, không đọc nội dung):");
      L.push("");
      for (const s of samples) L.push(`- ${mdCell(s.ref.title)} — ${code(s.ref.path)} (${s.reason})`);
    }
    if (q.key === "quiz") {
      L.push("");
      L.push(`Dữ kiện: ${fmtNum(r.questions)} câu hỏi nhận diện được, ${fmtNum(r.gradableQuestions)} chấm tự động được, ${fmtNum(Math.max(0, r.questions - r.gradableQuestions))} chưa có đáp án máy đọc được; ${fmtNum(r.gradableLessons)}/${fmtNum(r.lessons)} bài có ≥ 1 câu hỏi chấm được. Công cụ **không** kiểm tra đáp án đúng hay sai.`);
    }
    if (q.key === "order" && a.findings.orderUnclear.length) {
      L.push("");
      L.push(`Lưu ý: ${a.findings.orderUnclear.length} module có tên file không đánh số (${a.findings.orderUnclear.slice(0, 4).map((m) => `“${truncate(m, 30)}”`).join(", ")}${a.findings.orderUnclear.length > 4 ? ", …" : ""}) nên thứ tự bài hiển thị là theo bảng chữ cái, chưa chắc là thứ tự dạy.`);
    }
    L.push("");
  }
  L.push("- [ ] Ghi chú chung của người rà soát: …");
  L.push("");

  // ---- C
  L.push("## C. Gợi ý cải thiện (suy ra từ phần A, sắp theo mức ảnh hưởng đến điểm)");
  L.push("");
  if (!suggestions.length) {
    L.push("Không có gợi ý nào: mọi tiêu chí tự động đều đạt mục tiêu.");
    L.push("");
  } else {
    L.push(`Đường dẫn bài học bên dưới tính từ thư mục khóa ${code(c.dir)}. Công cụ chỉ đề xuất, không tự sửa file.`);
    L.push("");
    suggestions.forEach((s, i) => {
      L.push(`${i + 1}. **[${SEVERITY_LABEL[s.severity]}]** ${s.text} *(ước tính +${score1(s.gain)} điểm)*`);
      for (const ref of s.refs) L.push(`   - ${mdCell(ref.title)} — ${code(ref.path)}${ref.note ? ` *(${mdCell(ref.note)})*` : ""}`);
      if (s.more > 0) L.push(`   - … và ${fmtNum(s.more)} mục khác`);
    });
    L.push("");
  }
  L.push("---");
  L.push(`Cách tính điểm: xem mục “Phương pháp” trong [../QUALITY.md](../QUALITY.md).`);
  L.push("");
  return L.join("\n");
}

