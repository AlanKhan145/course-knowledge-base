    L.push(`| ${i + 1} | ${cell} | ${mdCell(truncate(c.domainTitle, 30))} | **${score1(it.a.score)}** | ${score1(areaScore(it.a, "metadata"))} | ${score1(areaScore(it.a, "structure"))} | ${score1(areaScore(it.a, "exercises"))} | ${score1(areaScore(it.a, "examples"))} | ${fmtNum(it.a.raw.lessons)} | ${mdCell(top)} |`);
