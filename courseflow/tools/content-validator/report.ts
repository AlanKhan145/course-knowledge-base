const SEVERITY_LABEL = { high: "Ưu tiên cao", medium: "Ưu tiên vừa", low: "Ưu tiên thấp" } as const;

function areaScore(a: Analysis, key: AreaKey): number {
  return a.areas.find((x) => x.key === key)?.score ?? 0;
}

function dateVi(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  const p = (n: number) => String(n).padStart(2, "0");
  return `${p(d.getDate())}/${p(d.getMonth() + 1)}/${d.getFullYear()} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

function score1(n: number): string {
  return fmtNum(n, 1);
}

