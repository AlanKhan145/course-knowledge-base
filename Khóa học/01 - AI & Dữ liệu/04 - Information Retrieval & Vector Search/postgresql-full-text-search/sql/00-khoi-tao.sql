-- Chuẩn hóa hai loại dữ liệu về một mô hình tài liệu thống nhất.
CREATE MATERIALIZED VIEW search_documents AS
SELECT
    'quote'::text AS source_type,
    q.id AS source_id,
    q.author AS title,
    q.content AS body,
    coalesce(tags.tags_text,'') AS metadata,
    setweight(to_tsvector('simple'::regconfig, coalesce(q.author,'')), 'A') ||
    setweight(to_tsvector('english'::regconfig, coalesce(q.content,'')), 'B') ||
    setweight(to_tsvector('simple'::regconfig, coalesce(tags.tags_text,'')), 'C')
    AS search_doc
FROM quotes q
LEFT JOIN LATERAL (
    SELECT string_agg(qt.tag, ' ' ORDER BY qt.tag) AS tags_text
    FROM quote_tags qt WHERE qt.quote_id = q.id
) tags ON TRUE
UNION ALL
SELECT
    'movie'::text AS source_type,
    m.id AS source_id,
    m.title,
    m.description AS body,
    concat_ws(' ', coalesce(a.actors,''), coalesce(g.genres,'')) AS metadata,
    setweight(to_tsvector('simple'::regconfig, coalesce(m.title,'')), 'A') ||
    setweight(to_tsvector('english'::regconfig, coalesce(m.description,'')), 'B') ||
    setweight(to_tsvector('simple'::regconfig,
        concat_ws(' ', coalesce(a.actors,''), coalesce(g.genres,''))), 'C')
    AS search_doc
FROM movies m
LEFT JOIN LATERAL (
    SELECT string_agg(ma.actor, ' ' ORDER BY ma.actor) AS actors
    FROM movie_actors ma WHERE ma.movie_id = m.id
) a ON TRUE
LEFT JOIN LATERAL (
    SELECT string_agg(mg.genre, ' ' ORDER BY mg.genre) AS genres
    FROM movie_genres mg WHERE mg.movie_id = m.id
) g ON TRUE;

CREATE UNIQUE INDEX search_documents_source_uidx
ON search_documents (source_type, source_id);
CREATE INDEX search_documents_search_gin
ON search_documents USING GIN (search_doc);

-- Từ điển gợi ý từ các lexeme. Từ đã stem có thể không phải cách viết đẹp nhất.
CREATE MATERIALIZED VIEW search_terms AS
SELECT word, ndoc, nentry
FROM ts_stat('SELECT search_doc FROM public.search_documents')
WHERE length(word) > 2;

CREATE UNIQUE INDEX search_terms_word_uidx ON search_terms (word);
CREATE INDEX search_terms_word_trgm_gin
ON search_terms USING GIN (word gin_trgm_ops);
